def _place(paths, x, y, height):
    width = height * ASPECT
    return [
        shape.custom([vec2(x + px * width, y + py * height) for px, py in path])
        for path in paths
    ]


def build(x, y, height):
    """Return (body, counter) shapes for the wordmark at x, y."""
    return _place(BODY, x, y, height), _place(COUNTER, x, y, height)


def width_for(height):
    return height * ASPECT
